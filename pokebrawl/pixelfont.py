ROWS = 9          # cell height (7 + descenders)
SPACE = 3
_cache = {}


def _glyph(ch, color, scale):
    key = (ch, color, scale)
    if key in _cache:
        return _cache[key]
    rows = _G.get(ch) or _G.get(ch.upper()) or _G["?"]
    w = max(len(r) for r in rows)
    s = pygame.Surface((w * scale, ROWS * scale), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                s.fill(color, (x * scale, y * scale, scale, scale))
    _cache[key] = s
    return s


def _real(kind="normal"):
    """FireRed's own font, once the graphics are downloaded (see frlg.py)."""
    from . import frlg
    return frlg.font(kind) if frlg.is_ready() else None


_WORDS = [("POKeMON", "Pokémon"), ("POKéMON", "Pokémon"), ("POKEMON", "Pokémon"), ("POKeDEX", "Pokédex"),
          ("POKéDEX", "Pokédex"), ("POKEDEX", "Pokédex"), ("POKe MART", "Poké Mart"), ("POKE MART", "Poké Mart"),
          ("POKe BALLS", "Poké Balls"), ("POKE BALLS", "POKé BALLS"), ("POKe BALL", "Poké Ball"),
          ("POKE BALL", "POKé BALL"), ("POKeBRAWL", "PokéBrawl"), ("POKe", "Poké"),
          ("Pokemon", "Pokémon"), ("Pokedex", "Pokédex"), ("Poke ", "Poké ")]


def _fix(text):
    """Writes Pokémon the normal way (not 'POKeMON')."""
    if "ok" not in text.lower():
        return text
    for a, b in _WORDS:
        text = text.replace(a, b)
    return text


def width(text, scale=2, small=False):
    f = _real("small" if small else "normal")
    if f:
        text = _fix(text)
        return sum((f.width(ch) if f.has(ch) else _old_width(ch) + 1) * scale for ch in text)
    text = _fix(text)
    w = 0
    for ch in text:
        if ch == " ":
            w += SPACE * scale
        else:
            rows = _G.get(ch) or _G.get(ch.upper()) or _G["?"]
            w += (max(len(r) for r in rows) + 1) * scale
    return max(0, w - scale)


def _old_width(ch):
    if ch == " ":
        return SPACE
    rows = _G.get(ch) or _G.get(ch.upper()) or _G["?"]
    return max(len(r) for r in rows)


def draw(surf, text, pos, color=(64, 64, 64), shadow=(216, 208, 176), scale=2, anchor="topleft", small=False):
    """GBA-style text: dark letters with a soft drop shadow to the right and below. small: FireRed's small font
    (healthboxes)."""
    x, y = pos
    w = width(text, scale, small)
    if anchor == "center":
        x -= w // 2
        y -= ROWS * scale // 2
    elif anchor == "topright":
        x -= w
    elif anchor == "midleft":
        y -= 7 * scale // 2
    elif anchor == "midright":
        x -= w
        y -= 7 * scale // 2
    f = _real("small" if small else "normal")
    if f:
        text = _fix(text)
        cx = x
        for ch in text:
            if f.has(ch):
                g = f.glyph(ch, tuple(color), tuple(shadow) if shadow else None, scale)
                surf.blit(g, (cx, y - f.top * scale))
                cx += f.width(ch) * scale
            else:
                if ch != " ":
                    surf.blit(_glyph(ch, color, scale), (cx, y))
                cx += (_old_width(ch) + 1) * scale
        return w
    text = _fix(text)
    cx = x
    for ch in text:
        if ch == " ":
            cx += SPACE * scale
            continue
        if shadow:
            surf.blit(_glyph(ch, shadow, scale), (cx + scale, y))
            surf.blit(_glyph(ch, shadow, scale), (cx, y + scale))
            surf.blit(_glyph(ch, shadow, scale), (cx + scale, y + scale))
        g = _glyph(ch, color, scale)
        surf.blit(g, (cx, y))
        cx += g.get_width() + scale
    return w


def wrap(text, max_w, scale=2):
    lines, line = [], ""
    for word in text.split(" "):
        test = (line + " " + word).strip()
        if width(test, scale) > max_w and line:
            lines.append(line)
            line = word
        else:
            line = test
    if line:
        lines.append(line)
    return lines
